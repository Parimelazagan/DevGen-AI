import { Router } from 'express';
import Groq from 'groq-sdk';
import { validatePortfolioOutput } from '../utils/portfolioSchema.js';

const router = Router();

const sendError = (res, status, code, error) => res.status(status).json({ error, code });
const DEFAULT_MODEL = 'openai/gpt-oss-20b';

function cleanJsonString(raw) {
  if (!raw) return '';
  let cleaned = raw.trim();
  cleaned = cleaned.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
  return cleaned;
}

router.post('/', async (req, res) => {
  try {
    const { githubData, resumeText, bioText, githubUsername } = req.body || {};

    if (![resumeText, bioText, githubData?.projects?.length].some(Boolean)) {
      return sendError(res, 400, 'NO_SOURCE_DATA', 'Provide a resume, bio, or at least one GitHub project before generating a portfolio.');
    }

    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey || apiKey === 'gsk_your_groq_api_key_here') {
      console.error('[Groq API Error]: GROQ_API_KEY environment variable is missing or placeholder in server/.env');
      return sendError(res, 500, 'AI_UNAVAILABLE', 'AI generation service is currently unavailable. Please try again.');
    }

    const projectsSummary = githubData?.projects ? JSON.stringify(githubData.projects, null, 2) : 'None';
    const resumeContent = resumeText ? resumeText.trim() : 'None';
    const additionalBio = bioText ? bioText.trim() : 'None';

    const prompt = `
You are an expert resume and portfolio data extraction AI.
Analyze the provided candidate source information (Resume Text, Additional Bio, and GitHub Projects) and extract a structured portfolio object.

SOURCE INFORMATION:
1. Additional Bio / Summary:
${additionalBio}

2. Raw Resume Text:
${resumeContent}

3. GitHub Projects Data (JSON):
${projectsSummary}

EXACT JSON OUTPUT SCHEMA:
{
  "personalInfo": {
    "name": "string",
    "title": "string",
    "photo": null,
    "location": "string or null"
  },
  "about": "string or null",
  "skills": ["array of strings"],
  "experience": [
    {
      "role": "string",
      "company": "string",
      "duration": "string",
      "description": "string"
    }
  ],
  "education": [
    {
      "degree": "string",
      "institution": "string",
      "duration": "string"
    }
  ],
  "projects": [
    {
      "title": "string",
      "description": "string",
      "tech": ["array of strings"],
      "link": "string or null"
    }
  ],
  "certifications": [
    {
      "name": "string",
      "issuer": "string",
      "date": "string"
    }
  ],
  "achievements": ["array of strings"],
  "contact": {
    "email": "string or null",
    "phone": "string or null"
  }
}

CRITICAL RULES:
1. If information for a field is not present in the provided text, use null for single values or an empty array [] for list values — do NOT invent, guess, or fabricate any information that isn't explicitly present in the source text.
2. For the projects field, use the GitHub projects data provided if available, and improve only the description wording to sound professional — do not change titles, tech, or links.
3. Return ONLY the JSON object, with no markdown code fences, no explanatory text before or after, and no additional commentary.
`;

    const groq = new Groq({ apiKey });
    const model = process.env.GROQ_MODEL || DEFAULT_MODEL;

    const completion = await groq.chat.completions.create({
      model,
      messages: [
        {
          role: 'user',
          content: prompt,
        },
      ],
      response_format: { type: 'json_object' },
    });

    const responseText = completion.choices[0]?.message?.content || '';

    let parsedData = null;

    // Attempt 1: Direct JSON.parse
    try {
      parsedData = JSON.parse(responseText);
    } catch (parseErr1) {
      console.warn('[LLM Parse Attempt 1 Failed]:', parseErr1.message);
      // Attempt 2: Clean markdown fences & retry
      try {
        const cleanedText = cleanJsonString(responseText);
        parsedData = JSON.parse(cleanedText);
      } catch (parseErr2) {
        console.error('[LLM Parse Attempt 2 Failed]:', parseErr2.message);
        return sendError(res, 502, 'INVALID_AI_RESPONSE', 'Failed to generate structured portfolio data. Please try again.');
      }
    }

    const validation = validatePortfolioOutput(parsedData);
    if (!validation.valid) {
      console.error('[Portfolio Validation Error]:', validation.error);
      return sendError(res, 502, 'INVALID_AI_RESPONSE', 'The AI returned an invalid portfolio response. Please try again.');
    }

    // Merge trusted GitHub metadata, which is not generated by the LLM.
    const githubStats = githubData?.githubStats || null;
    const socialLinks = {
      github: githubUsername ? `https://github.com/${githubUsername}` : null,
      linkedin: null,
      twitter: null,
      website: null,
    };

    const finalPortfolioData = {
      ...validation.data,
      projects: validation.data.projects.map((project) => {
        const sourceProject = githubData?.projects?.find((item) => item.link === project.link || item.title === project.title);
        return sourceProject?.metadata ? { ...project, metadata: sourceProject.metadata } : project;
      }),
      githubStats,
      socialLinks,
    };

    return res.json(finalPortfolioData);
  } catch (apiError) {
    console.error('[Groq API Route Error]:', apiError.message || apiError);
    if (apiError?.status === 404 && /model/i.test(apiError.message || '')) {
      return sendError(res, 502, 'MODEL_UNAVAILABLE', 'The configured AI model is unavailable. Set GROQ_MODEL to a model available to your Groq account.');
    }
    return sendError(res, 502, 'AI_UNAVAILABLE', 'AI generation service is currently unavailable. Please try again.');
  }
});

export default router;
